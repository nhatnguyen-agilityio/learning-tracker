#!/bin/bash
# PreToolUse (matcher: Write|Edit|MultiEdit|NotebookEdit): block edits to protected files.
# Exit 0 = allow. Exit 2 = block; stderr is shown to Claude. Fails closed.
block() { echo "Blocked: $1" >&2; exit 2; }

command -v jq >/dev/null || block "jq is missing, so the edit can't be checked."
command -v python3 >/dev/null || block "python3 is missing, so the edit can't be checked."
input=$(cat)
jq -e 'type == "object"' <<<"$input" >/dev/null 2>&1 || block "the input couldn't be read."
file=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // empty' <<<"$input")
[ -z "$file" ] && exit 0
cwd=$(jq -r '.cwd // empty' <<<"$input")

# Compare real paths, so "..", symlinks and letter case can't get around it.
rel=$(cd "${cwd:-$PWD}" && python3 -I -c '
import os, sys
real = lambda p: os.path.realpath(p).lower()
print(os.path.relpath(real(sys.argv[1]), real(sys.argv[2])))' "$file" "${CLAUDE_PROJECT_DIR:-$PWD}") \
  || block "the path couldn't be resolved."

case "$rel" in
  supabase/seed.sql) block "supabase/seed.sql is shared seed data. Ask the user to approve the change." ;;
  src/components/ui/*) block "src/components/ui is generated by shadcn. Wrap the component instead." ;;
  .env.sample) exit 0 ;;
  .env|.env.*) block "real .env files stay out of Claude's edits." ;;
esac
exit 0
